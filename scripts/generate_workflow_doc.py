"""Generate the human-readable workflow reference from the model and service tables."""

import argparse
import ast
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SERVICES = ROOT / "apps/workflow/services.py"
MODELS = ROOT / "apps/complaints/models.py"
OUTPUT = ROOT / "docs/WORKFLOW.md"

ROLE_LABELS = {
    "system": "System",
    "citizen": "Citizen",
    "triage_reviewer": "Triage reviewer",
    "department_official": "Department official",
    "supervisor": "Supervisor",
    "field_worker": "Field worker",
    "admin": "Admin",
}
TERMINAL_STATUSES = {"verified_closed", "rejected", "cancelled"}


def status_choices():
    tree = ast.parse(MODELS.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "Complaint":
            status_class = next(
                child for child in node.body
                if isinstance(child, ast.ClassDef) and child.name == "Status"
            )
            return [
                (ast.literal_eval(value.value.elts[0]), ast.literal_eval(value.value.elts[1]))
                for value in status_class.body
                if isinstance(value, ast.Assign)
                and isinstance(value.targets[0], ast.Name)
                and isinstance(value.value, ast.Tuple)
            ]
    raise ValueError("Complaint.Status choices were not found")


def transitions():
    tree = ast.parse(SERVICES.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "TRANSITIONS"
            for target in node.targets
        ):
            raw = ast.literal_eval(node.value)
            return {
                (source, destination): tuple(sorted(roles))
                for (source, destination), roles in raw.items()
            }
    raise ValueError("TRANSITIONS table was not found")


def render():
    statuses = status_choices()
    transition_table = transitions()
    outgoing = {key: [] for key, _label in statuses}
    for (source, destination), roles in transition_table.items():
        outgoing[source].append((destination, roles))

    lines = [
        "<!-- Generated by scripts/generate_workflow_doc.py. Do not edit this file directly. -->",
        "# Complaint workflow",
        "",
        "This reference is generated from `Complaint.Status` and `TRANSITIONS` in `apps/workflow/services.py`. "
        "All status changes must go through `transition()`.",
        "",
        "## Statuses and allowed outgoing transitions",
        "",
        "| Status | Allowed transitions |",
        "|---|---|",
    ]
    for status, label in statuses:
        choices = [
            f"`{destination}` ({', '.join(ROLE_LABELS[role] for role in roles)})"
            for destination, roles in outgoing[status]
        ]
        value = "; ".join(choices) if choices else "None (terminal)"
        if status not in TERMINAL_STATUSES and not choices:
            value = "None"
        lines.append(f"| `{status}` — {label} | {value} |")

    lines += [
        "",
        "## Transition matrix",
        "",
        "| From | To | Allowed role(s) |",
        "|---|---|---|",
    ]
    for (source, destination), roles in sorted(transition_table.items()):
        lines.append(
            f"| `{source}` | `{destination}` | "
            f"{', '.join(ROLE_LABELS[role] for role in roles)} |"
        )
    lines += [
        "",
        "## Design comparison",
        "",
        "The approved V2 design in `docs/ROADMAP_V2.md` task 1.4 and `docs/SPEC.md` permits an admin to cancel any "
        "non-terminal complaint with a reason, recorded as an `admin_override`. The earlier base transition table "
        "in `AGENTS.md` listed citizen cancellation but did not include that admin recovery operation. The current "
        "table implements the later approved V2 rule. The remaining roles and transitions match the designed "
        "workflow: citizens may cancel in any pre-acknowledgement state, including while information is requested; "
        "field workers make the completion claim, and citizens or "
        "supervisors explicitly verify or reopen it. No system transition closes a complaint after citizen silence.",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated document is out of date")
    args = parser.parse_args()
    generated = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            raise SystemExit("docs/WORKFLOW.md is out of date; run python scripts/generate_workflow_doc.py")
        return
    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
